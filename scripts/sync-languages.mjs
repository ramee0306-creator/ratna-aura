// Rewrites app/src/i18n/translations.ts so it imports every language whose six translation files exist
// (locales/<code>.ts, numerology.<code>.ts, kundli.<code>.ts, jyotish.<code>.ts, ai.<code>.ts, extra.<code>.ts),
// in the order of app/src/i18n/languages.ts.
//
//   npm run sync-languages
//
// The test app/src/i18n/translations.test.ts then checks each one is complete.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const i18n = join(root, 'app', 'src', 'i18n');
const locales = join(i18n, 'locales');

const codes = [...readFileSync(join(i18n, 'languages.ts'), 'utf8').matchAll(/\{ code: '([^']+)'/g)].map((m) => m[1]);
const ready = codes.filter((c) => ['', 'numerology.', 'kundli.', 'jyotish.', 'ai.', 'extra.'].every((p) => existsSync(join(locales, `${p}${c}.ts`))));

const ident = (code) => `lang_${code.replace(/-/g, '_')}`;
const lines = [
  '// Every finished translation. A language listed in languages.ts appears in the app',
  '// as soon as its file is imported here. Generated by "npm run sync-languages" — do not edit by hand.',
  "import type { LanguageCode } from './languages';",
  "import { type Translation } from './locales/en';",
  ...ready.map((c) => `import ${ident(c)} from './locales/${c}';`),
  '',
  'export const TRANSLATIONS: Partial<Record<LanguageCode, Translation>> = {',
  ...ready.map((c) => `  '${c}': ${ident(c)},`),
  '};',
  '',
];
writeFileSync(join(i18n, 'translations.ts'), lines.join('\n'));
console.log(`${ready.length} languages: ${ready.join(' ')}`);
